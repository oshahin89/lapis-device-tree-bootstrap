/*
 * lapis NT38771 load over the real SPI3 controller (shim alternate main,
 * build.sh tspi).
 *
 * tnvt showed that a byte-identical load bit-banged over GPIO (4-5 s from
 * xnu, 0.8 s from the shim) never boots the NT38771 firmware, while
 * Android's load through the MTK SPI controller (~130 ms reset->BOOT_RDY)
 * does. This probe drives the controller itself, the way the stock
 * spi-mt65xx (mediatek,mt6989-spi: ipm_design, enhance_timing, sw_cs,
 * enhance_packet_len, need_pad_sel) does in PIO mode:
 *
 * 1. Clocks, from clk-mt6878(.c/-peri.c) and the runtime FDT
 *    (clocks = <topckgen UNIVPLL_D6_D2>, <topckgen SPI3_SEL>, <pericfg_ao SPI3_B>):
 *      topckgen 0x10000000 CLK_CFG_4 (+0x50, SET +0x54, CLR +0x58):
 *        spi3_sel = bits 8..10 <- 1 (univpll_d6_d2 = univpll/12),
 *        pdn bit 15 cleared; CLK_CFG_UPDATE (+0x04) bit 17.
 *      pericfg_ao 0x11036000 CG0: CLR +0x28 bit 15 opens peraop_spi3_b
 *        (status +0x10, 1 = gated).
 *    SPI registers are only touched after the gate reads open.
 * 2. Pins 68..71 (SPI3 CLK/CSB/MOSI/MISO) -> function 2, as Android's
 *    pinctrl default state (0x4402..0x4702). GPIO 90 is never touched.
 * 3. Controller: CMD = NONIDLE | CS_PIN_SEL | TXMSBF | RXMSBF, tickdly 2
 *    (FDT mediatek,tickdly), PAD_SEL 0, CFG2 SCK high/low = 10 -> 22 ticks
 *    (208 MHz / 22 = 9.45 MHz, Android's 9.6 MHz request rounded).
 *    Messages: CS_POL set = CS asserted (sw_cs), 32-byte FIFO packets,
 *    full duplex (CFG3 = 0), poll STATUS1, drain RX; release = CS_POL clear
 *    + CMD_RST (clears CS_PIN_SEL), like mtk_spi_set_cs.
 * 4. Chip ID; if NT38771, Android's cold load (reset 0x69, banks, all 15
 *    partitions, BOOT_RDY), timed, then the reset-state poll.
 */
#include <stdint.h>
#include "console.h"
#include "nvt_fw.h"		/* generated by build.sh: nvt_fw[196608] */

#define rsr(r) ({ uint64_t _v; __asm__ volatile("mrs %0, " r : "=r"(_v)); _v; })

#define TOPCK		0x10000000UL
#define CLK_CFG_UPDATE	0x004
#define CLK_CFG_4	0x050
#define CLK_CFG_4_SET	0x054
#define CLK_CFG_4_CLR	0x058
#define SPI3_UPD	(1u << 17)

#define PERAO		0x11036000UL
#define PERAO_CG0_STA	0x010
#define PERAO_CG0_SET	0x024
#define PERAO_CG0_CLR	0x028
#define SPI3_CG		(1u << 15)

#define GPIO		0x10005000UL
#define GPIO_MODE	0x380		/* pins 64..71, 4 bits each */

#define SPI		0x11013000UL
#define SPI_CFG0	0x00
#define SPI_CFG1	0x04
#define SPI_TX_DATA	0x10
#define SPI_RX_DATA	0x14
#define SPI_CMD		0x18
#define SPI_STATUS0	0x1c
#define SPI_STATUS1	0x20
#define SPI_PAD_SEL	0x24
#define SPI_CFG2	0x28
#define SPI_CFG3	0x40
#define SPI_CFG5	0x68

#define CMD_ACT		(1u << 0)
#define CMD_RST		(1u << 2)
#define CMD_DEASSERT	(1u << 5)
#define CMD_SAMPLE_SEL	(1u << 6)
#define CMD_CS_POL	(1u << 7)
#define CMD_CPHA	(1u << 8)
#define CMD_CPOL	(1u << 9)
#define CMD_RX_DMA	(1u << 10)
#define CMD_TX_DMA	(1u << 11)
#define CMD_TXMSBF	(1u << 12)
#define CMD_RXMSBF	(1u << 13)
#define CMD_RX_ENDIAN	(1u << 14)
#define CMD_TX_ENDIAN	(1u << 15)
#define CMD_FINISH_IE	(1u << 16)
#define CMD_PAUSE_IE	(1u << 17)
#define CMD_CS_PIN_SEL	(1u << 18)
#define CMD_NONIDLE	(1u << 19)
#define CMD_LOOP	(1u << 21)
#define CMD_TICKDLY_SH	22
#define CMD_TICKDLY_MSK	(7u << 22)

#define SCK_TICKS	11u		/* half period in spi_clk ticks */
#define TICK_DLY	2u
#define FIFO		32u

#define NVT_CHIP_ID	0x3f004u
#define NVT_RESET	0x3f0feu
#define NVT_BOOT_READY	0x3f102u
#define NVT_EVENT_BUF	0x2b400u
#define NVT_XFER_MAX	(15u * 1024u)

static inline uint32_t rd(uintptr_t a) { return *(volatile uint32_t *)a; }
static inline void wr(uintptr_t a, uint32_t v)
{
	*(volatile uint32_t *)a = v;
	__asm__ volatile("dsb sy" ::: "memory");
}

static uint64_t ticks(void) { return rsr("cntvct_el0"); }
static uint32_t us_since(uint64_t t0)
{
	return (uint32_t)((ticks() - t0) * 1000000ull / rsr("cntfrq_el0"));
}
static void udelay(uint32_t us)
{
	uint64_t f = rsr("cntfrq_el0"), t0 = ticks();
	while (ticks() - t0 < (f / 1000000) * us + 1)
		;
}

static uint32_t n_timeouts, last_st0;

/* mtk_spi_prepare_message for mode 0, MSB first, active-low CS. */
static void spi_prepare(void)
{
	uint32_t c = rd(SPI + SPI_CMD);
	c |= CMD_NONIDLE | CMD_CS_PIN_SEL | CMD_TXMSBF | CMD_RXMSBF;
	c &= ~(CMD_LOOP | CMD_CPHA | CMD_CPOL | CMD_RX_ENDIAN | CMD_TX_ENDIAN |
	       CMD_CS_POL | CMD_SAMPLE_SEL | CMD_TX_DMA | CMD_RX_DMA |
	       CMD_DEASSERT | CMD_FINISH_IE | CMD_PAUSE_IE | CMD_TICKDLY_MSK);
	c |= TICK_DLY << CMD_TICKDLY_SH;
	wr(SPI + SPI_CMD, c);
	wr(SPI + SPI_PAD_SEL, 0);
	wr(SPI + SPI_CFG2, ((SCK_TICKS - 1) << 16) | (SCK_TICKS - 1));
	wr(SPI + SPI_CFG3, 0);		/* full duplex, single bit */
}

static void spi_cs(int assert)
{
	uint32_t c = rd(SPI + SPI_CMD);
	if (assert) {
		wr(SPI + SPI_CMD, c | CMD_CS_POL);
		return;
	}
	c &= ~CMD_CS_POL;
	wr(SPI + SPI_CMD, c);
	/* mtk_spi_reset */
	wr(SPI + SPI_CMD, rd(SPI + SPI_CMD) | CMD_RST);
	wr(SPI + SPI_CMD, rd(SPI + SPI_CMD) & ~(CMD_RST | CMD_CS_PIN_SEL));
}

/* One FIFO packet (<= 32 bytes), full duplex. */
static void spi_packet(const uint8_t *tx, uint8_t *rx, uint32_t n)
{
	uint32_t cfg1 = rd(SPI + SPI_CFG1) & ~0xffffff00u;	/* keep CS idle */
	wr(SPI + SPI_CFG1, cfg1 | ((n - 1) << 16));
	wr(SPI + SPI_CFG5, 0);
	for (uint32_t i = 0; i < n; i += 4) {
		uint32_t w = 0;
		for (uint32_t k = 0; k < 4 && i + k < n; k++)
			w |= (uint32_t)(tx ? tx[i + k] : 0) << (8 * k);
		wr(SPI + SPI_TX_DATA, w);
	}
	wr(SPI + SPI_CMD, rd(SPI + SPI_CMD) | CMD_ACT);
	uint64_t f = rsr("cntfrq_el0"), t0 = ticks();
	while (!rd(SPI + SPI_STATUS1)) {
		if (ticks() - t0 > f / 100) {		/* 10 ms */
			n_timeouts++;
			break;
		}
	}
	last_st0 = rd(SPI + SPI_STATUS0);
	for (uint32_t i = 0; i < n; i += 4) {
		uint32_t w = rd(SPI + SPI_RX_DATA);
		for (uint32_t k = 0; k < 4 && i + k < n; k++)
			if (rx)
				rx[i + k] = (uint8_t)(w >> (8 * k));
	}
}

/* One CS assertion: hdr bytes, then a body sent from tx or read into rx. */
static void message(const uint8_t *hdr, uint32_t nh, const uint8_t *tx, uint8_t *rx, uint32_t n)
{
	uint8_t buf[FIFO], in[FIFO];
	spi_prepare();
	spi_cs(1);
	uint32_t total = nh + n, pos = 0;
	while (pos < total) {
		uint32_t len = total - pos > FIFO ? FIFO : total - pos;
		for (uint32_t i = 0; i < len; i++) {
			uint32_t p = pos + i;
			buf[i] = p < nh ? hdr[p] : (tx ? tx[p - nh] : 0);
		}
		spi_packet(buf, in, len);
		if (rx)
			for (uint32_t i = 0; i < len; i++)
				if (pos + i >= nh)
					rx[pos + i - nh] = in[i];
		pos += len;
	}
	spi_cs(0);
}

static void set_page(uint32_t addr)
{
	uint8_t h[3] = { 0xff, (uint8_t)(addr >> 15), (uint8_t)(addr >> 7) };
	message(h, 3, 0, 0, 0);
}

static void nvt_write(uint32_t addr, const uint8_t *data, uint32_t len)
{
	uint8_t h = (uint8_t)((addr & 0x7f) | 0x80);
	set_page(addr);
	message(&h, 1, data, 0, len);
}

static void nvt_write_u8(uint32_t addr, uint8_t v) { nvt_write(addr, &v, 1); }

/* Read: address byte, one dummy, then the payload. */
static void nvt_read(uint32_t addr, uint8_t *out, uint32_t len)
{
	uint8_t h[2] = { (uint8_t)(addr & 0x7f), 0 };
	set_page(addr);
	message(h, 2, 0, out, len);
}

static uint32_t le32(const uint8_t *p)
{
	return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) |
	       ((uint32_t)p[3] << 24);
}

struct part { uint32_t bin, sram, size, crc; };

/* Same partition walk as sweet_nt38771.c / tnvt.c. */
static int parse(struct part *p, unsigned *count)
{
	const uint8_t *fw = nvt_fw;
	uint32_t end = le32(fw), pos;
	if (fw[0x2f000] + fw[0x2f001] != 0xff || end < 0x30 || end > sizeof(nvt_fw))
		return 0;
	for (pos = 0x30; pos + 16 <= end; pos += 16) {
		if (le32(fw + pos + 4) != 0 && le32(fw + pos + 8) == 0) {
			end = pos + 16;
			break;
		}
	}
	unsigned n = (end - 0x30) / 16;
	if (n == 0 || n > 16)
		return 0;
	p[0] = (struct part){ le32(fw), le32(fw + 4), le32(fw + 8), le32(fw + 0x18) };
	p[1] = (struct part){ le32(fw + 12), le32(fw + 16), le32(fw + 20), le32(fw + 0x1c) };
	for (unsigned i = 0; i < n; i++) {
		const uint8_t *e = fw + 0x30 + i * 16;
		p[2 + i] = (struct part){ le32(e + 8), le32(e), le32(e + 4), le32(e + 12) };
	}
	*count = 2 + n;
	for (unsigned i = 0; i < *count; i++)
		if (p[i].size && p[i].bin + p[i].size + 1 > sizeof(nvt_fw))
			return 0;
	return 1;
}

static void crc_bank(uint32_t des, uint32_t len_reg, uint32_t golden, const struct part *p)
{
	uint8_t b[4];
	b[0] = (uint8_t)p->sram; b[1] = (uint8_t)(p->sram >> 8); b[2] = (uint8_t)(p->sram >> 16);
	nvt_write(des, b, 3);
	b[0] = (uint8_t)p->size; b[1] = (uint8_t)(p->size >> 8); b[2] = (uint8_t)(p->size >> 16);
	nvt_write(len_reg, b, 3);
	b[0] = (uint8_t)p->crc; b[1] = (uint8_t)(p->crc >> 8);
	b[2] = (uint8_t)(p->crc >> 16); b[3] = (uint8_t)(p->crc >> 24);
	nvt_write(golden, b, 4);
}

static void dump_spi(const char *tag)
{
	con_hex2(tag, "cmd=", rd(SPI + SPI_CMD), "cfg0=", rd(SPI + SPI_CFG0));
	con_hex2(tag, "cfg1=", rd(SPI + SPI_CFG1), "cfg2=", rd(SPI + SPI_CFG2));
	con_hex2(tag, "cfg3=", rd(SPI + SPI_CFG3), "st0=", rd(SPI + SPI_STATUS0));
}

void shim_main(uint64_t dtb, uint64_t entry_el)
{
	struct part parts[18];
	unsigned count = 0;
	uint8_t id[6], st[6], fwi[2];
	(void)dtb; (void)entry_el;

	con_clear(BLUE);
	con_str("LAPIS", "tspi v3: SPI3 load + live touch reports");
	con_skip();

	/* 1. clocks */
	uint32_t cfg4 = rd(TOPCK + CLK_CFG_4), cg0 = rd(PERAO + PERAO_CG0_STA);
	con_hex2("CLK0", "cfg4=", cfg4, "perao_cg0=", cg0);
	wr(TOPCK + CLK_CFG_4_CLR, (7u << 8) | (1u << 15));	/* sel 0, pdn off */
	wr(TOPCK + CLK_CFG_4_SET, 1u << 8);			/* sel 1 = univpll_d6_d2 */
	wr(TOPCK + CLK_CFG_UPDATE, SPI3_UPD);
	udelay(100);
	wr(PERAO + PERAO_CG0_CLR, SPI3_CG);
	udelay(100);
	cfg4 = rd(TOPCK + CLK_CFG_4);
	cg0 = rd(PERAO + PERAO_CG0_STA);
	con_hex2("CLK1", "cfg4=", cfg4, "perao_cg0=", cg0);
	if (((cfg4 >> 8) & 0x87) != 0x01 || (cg0 & SPI3_CG)) {
		con_str("FAIL", "SPI3 clock did not open; SPI regs left alone");
		goto out;
	}

	/* 2. pins 68..71 -> SPI3 (function 2) */
	uint32_t mode = rd(GPIO + GPIO_MODE);
	wr(GPIO + GPIO_MODE, (mode & 0x0000ffffu) | 0x22220000u);
	con_hex2("PINS", "mode_before=", mode, "after=", rd(GPIO + GPIO_MODE));

	/* 3. controller */
	dump_spi("SPI0");
	wr(SPI + SPI_CMD, rd(SPI + SPI_CMD) | CMD_RST);
	wr(SPI + SPI_CMD, rd(SPI + SPI_CMD) & ~(CMD_RST | CMD_CS_PIN_SEL));
	spi_prepare();
	dump_spi("SPI1");
	con_skip();

	/* speed check: one 1 KiB message of zeros (first byte 0x00 = a read of
	 * 0x3F000, the rest is clocked-out dummy: no chip state changes) */
	uint64_t t0 = ticks();
	{
		static const uint8_t z[1024];
		set_page(NVT_CHIP_ID);
		message(0, 0, z, 0, sizeof(z));
	}
	uint32_t us1k = us_since(t0);

	/* 4a. plain ID read first (like tchip), then Android's chip check */
	nvt_read(NVT_CHIP_ID, id, 6);
	con_hex2("ID0", "id345=", ((uint32_t)id[3] << 16) | (id[4] << 8) | id[5],
		 "timeouts=", n_timeouts);
	nvt_write_u8(NVT_RESET, 0x69);
	udelay(5000);
	for (int i = 0; i < 6; i++)
		id[i] = 0;
	nvt_write(NVT_CHIP_ID, id, 6);
	nvt_read(NVT_CHIP_ID, id, 6);
	con_hex2("CHIP", "id345=", ((uint32_t)id[3] << 16) | (id[4] << 8) | id[5],
		 "us/KiB=", us1k);
	con_hex2("XFER", "timeouts=", n_timeouts, "st0=", last_st0);
	if (id[4] != 0x87 || id[5] != 0x03) {
		con_str("FAIL", "chip ID mismatch over the controller");
		dump_spi("SPI2");
		goto out;
	}
	if (!parse(parts, &count)) {
		con_str("FAIL", "firmware table rejected");
		goto out;
	}
	udelay(1000000);		/* Android: ~1 s from chip check to load */
	con_hex2("PARTS", "count=", count, "ilm_size=", parts[0].size + 1);

	/* 4b. Android's cold load (full ILM), timed reset -> BOOT_RDY */
	uint64_t tr = ticks();
	nvt_write_u8(NVT_RESET, 0x69);
	udelay(5000);
	crc_bank(0x3f7b4, 0x3f7b8, 0x3f7bc, &parts[0]);
	crc_bank(0x3fb84, 0x3fb88, 0x3fb8c, &parts[1]);
	for (unsigned i = 0; i < count; i++) {
		uint32_t left = parts[i].size ? parts[i].size + 1 : 0;
		uint32_t bin = parts[i].bin, sram = parts[i].sram;
		while (left) {
			uint32_t n = left > NVT_XFER_MAX ? NVT_XFER_MAX : left;
			nvt_write(sram, nvt_fw + bin, n);
			left -= n;
			bin += n;
			sram += n;
		}
	}
	nvt_write_u8(NVT_EVENT_BUF + 0x60, 0x00);
	nvt_write_u8(NVT_EVENT_BUF + 0x50, 0xae);
	nvt_write_u8(NVT_BOOT_READY, 1);
	uint32_t load_ms = us_since(tr) / 1000;
	udelay(5000);

	uint32_t t_ok = 0, state = 0;
	uint64_t tp = ticks();
	for (int i = 0; i < 100; i++) {
		nvt_read(NVT_EVENT_BUF + 0x60, st, 6);
		state = st[0];
		if (state >= 0xa0 && state <= 0xaf) {
			t_ok = us_since(tp) / 1000 + 1;
			break;
		}
		udelay(10000);
	}
	nvt_read(NVT_EVENT_BUF + 0x78, fwi, 2);
	con_hex2("LOAD", "reset->rdy_ms=", load_ms, "timeouts=", n_timeouts);
	con_hex2("STATE", "state=", state, "ok_after_ms=", t_ok);
	con_hex2("FWINFO", "ver/~ver=", ((uint32_t)fwi[0] << 8) | fwi[1],
		 "st1..3=", ((uint32_t)st[1] << 16) | (st[2] << 8) | st[3]);
	con_str("KEY ", (state >= 0xa0 && state <= 0xaf) ?
		"FIRMWARE BOOTED over the SPI controller" :
		"still not booted with the controller");
	if (state < 0xa0 || state > 0xaf)
		goto out;

	/* v3: live report polling like Android's IRQ read (108 bytes at offset 0
	 * of the event page), every 10 ms, for 10 minutes. Contact record =
	 * id<<3|state, X hi/lo, Y hi/lo (big-endian), size; checksum = -sum of
	 * payload[0..63] at payload[64]. Touch the screen and watch the lines. */
	con_skip();
	con_str("TOUCH", "polling 108-byte reports every 10 ms; touch the screen");
	int live = con_row();
	uint32_t polls = 0, good = 0, bad = 0, touched = 0;
	uint32_t lx = 0, ly = 0, lid = 0;
	uint8_t rep[108], head[6] = { 0 };
	for (uint64_t t_end = ticks() + rsr("cntfrq_el0") * 600; ticks() < t_end; ) {
		nvt_read(NVT_EVENT_BUF, rep, sizeof(rep));
		polls++;
		uint8_t sum = 0;
		for (int i = 0; i < 64; i++)
			sum = (uint8_t)(sum + rep[i]);
		if (rep[64] == (uint8_t)(0u - sum)) {
			good++;
			for (int c = 0; c < 10; c++) {
				const uint8_t *r = rep + c * 6;
				uint32_t s = r[0] & 7, id = r[0] >> 3;
				if (s >= 1 && s <= 4 && id >= 1 && id <= 10) {
					touched++;
					lid = r[0];
					lx = ((uint32_t)r[1] << 8) | r[2];
					ly = ((uint32_t)r[3] << 8) | r[4];
					break;
				}
			}
		} else {
			bad++;
		}
		for (int i = 0; i < 6; i++)
			head[i] = rep[i];
		if (polls % 10 == 0) {		/* ~10 screen updates per second */
			con_set_row(live);
			con_hex2("POLL", "good=", good, "bad=", bad);
			con_hex2("CONTACT", "frames=", touched, "id/st=", lid);
			con_hex2("XY", "x=", lx, "y=", ly);
			con_hex2("NATIVE", "x=", lx / 16, "y=", ly / 16);
			con_hex2("HEAD", "", ((uint32_t)head[0] << 24) | ((uint32_t)head[1] << 16) |
				 ((uint32_t)head[2] << 8) | head[3],
				 "", ((uint32_t)head[4] << 8) | head[5]);
		}
		udelay(10000);
	}
	con_str("TOUCH", "10 minutes over");
out:
	con_str("DONE", "Power+Vol-down to recover");
	for (;;)
		__asm__ volatile("wfe");
}

void exc_report(uint64_t slot, uint64_t esr, uint64_t elr, uint64_t far)
{
	con_skip();
	con_hex("EXC slot", slot);
	con_hex("ESR", esr);
	con_hex("ELR", elr);
	con_hex("FAR", far);
	for (;;)
		__asm__ volatile("wfe");
}

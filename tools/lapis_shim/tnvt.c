/*
 * lapis NT38771 fast-download probe (shim alternate main, build.sh tnvt).
 *
 * The XNU driver's firmware load is byte-identical to Android's (same
 * 0x2B image, same reset, chip check, CRC banks, partitions, CRC enable,
 * BOOT_RDY; the chip even reports Android's bootloader CRC flags 0x0018),
 * yet the firmware never boots. What is left is the transport: Android
 * uses the MTK SPI controller (~9.6 MHz, reset -> BOOT_RDY in ~130 ms);
 * the driver bit-bangs at ~250 kHz with a 2 us delay per edge (seconds).
 * Hypothesis: the bootloader only accepts BOOT_RDY within a window after
 * the 0x69 reset. This probe bit-bangs as fast as the GPIO block allows
 * (two DO writes per bit, no delays), times reset -> BOOT_RDY, and shows
 * the reset state. GPIO 90 (shared panel/touch reset) is never touched.
 */
#include <stdint.h>
#include "console.h"
#include "nvt_fw.h"		/* generated by build.sh: nvt_fw[196608] */

#define rsr(r) ({ uint64_t _v; __asm__ volatile("mrs %0, " r : "=r"(_v)); _v; })

#define GPIO		0x10005000UL
#define GPIO_MODE	0x380		/* pins 64..71, 4 bits each */
#define GPIO_DIR	0x020		/* pins 64..95 */
#define GPIO_DO		0x120
#define GPIO_DI		0x220
#define CLK		(1u << 4)	/* GPIO68 */
#define CS		(1u << 5)	/* GPIO69 */
#define MOSI		(1u << 6)	/* GPIO70 */
#define MISO		(1u << 7)	/* GPIO71 */

#define NVT_CHIP_ID	0x3f004u
#define NVT_RESET	0x3f0feu
#define NVT_BOOT_READY	0x3f102u
#define NVT_EVENT_BUF	0x2b400u
#define NVT_XFER_MAX	(15u * 1024u)

static inline uint32_t rd(uintptr_t a) { return *(volatile uint32_t *)a; }
static inline void wr(uintptr_t a, uint32_t v) { *(volatile uint32_t *)a = v; }

static uint64_t ticks(void) { return rsr("cntvct_el0"); }
static uint32_t us_since(uint64_t t0)
{
	return (uint32_t)((ticks() - t0) * 1000000ull / rsr("cntfrq_el0"));
}
static void udelay(uint32_t us)
{
	uint64_t f = rsr("cntfrq_el0"), t0 = ticks();
	while (ticks() - t0 < (f / 1000000) * us + 1)
		;
}

/* DO value with our four pins idle (CS high, CLK/MOSI low); the other bits
 * of the bank are read once and kept, so each edge is one plain write. */
static uint32_t do_idle;

static void cs_low(void) { wr(GPIO + GPIO_DO, do_idle & ~CS); }
static void cs_high(void)
{
	wr(GPIO + GPIO_DO, do_idle & ~CS);
	wr(GPIO + GPIO_DO, do_idle);
}

/* Mode 0: MOSI changes while CLK is low, the slave samples on the rise. */
static void tx_byte(uint8_t b)
{
	uint32_t lo = do_idle & ~CS;
	for (int bit = 7; bit >= 0; bit--) {
		uint32_t w = lo | ((b >> bit) & 1 ? MOSI : 0);
		wr(GPIO + GPIO_DO, w);
		wr(GPIO + GPIO_DO, w | CLK);
	}
	wr(GPIO + GPIO_DO, lo);
}

static uint8_t rx_byte(void)
{
	uint32_t lo = do_idle & ~CS;
	uint8_t in = 0;
	for (int bit = 7; bit >= 0; bit--) {
		wr(GPIO + GPIO_DO, lo);
		wr(GPIO + GPIO_DO, lo | CLK);
		in = (uint8_t)((in << 1) | ((rd(GPIO + GPIO_DI) & MISO) != 0));
	}
	wr(GPIO + GPIO_DO, lo);
	return in;
}

static void set_page(uint32_t addr)
{
	cs_low();
	tx_byte(0xff);
	tx_byte((uint8_t)(addr >> 15));
	tx_byte((uint8_t)(addr >> 7));
	cs_high();
}

static void nvt_write(uint32_t addr, const uint8_t *data, uint32_t len)
{
	set_page(addr);
	cs_low();
	tx_byte((uint8_t)((addr & 0x7f) | 0x80));
	for (uint32_t i = 0; i < len; i++)
		tx_byte(data[i]);
	cs_high();
}

static void nvt_write_u8(uint32_t addr, uint8_t v) { nvt_write(addr, &v, 1); }

/* Read: address byte, one dummy, then the payload. */
static void nvt_read(uint32_t addr, uint8_t *out, uint32_t len)
{
	set_page(addr);
	cs_low();
	tx_byte((uint8_t)(addr & 0x7f));
	(void)rx_byte();
	for (uint32_t i = 0; i < len; i++)
		out[i] = rx_byte();
	cs_high();
}

static uint32_t le32(const uint8_t *p)
{
	return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) |
	       ((uint32_t)p[3] << 24);
}

struct part { uint32_t bin, sram, size, crc; };

/* Same partition walk as sweet_nt38771.c / nt387xx_fw_update.c. */
static int parse(struct part *p, unsigned *count)
{
	const uint8_t *fw = nvt_fw;
	uint32_t end = le32(fw), pos;
	if (fw[0x2f000] + fw[0x2f001] != 0xff || end < 0x30 || end > sizeof(nvt_fw))
		return 0;
	for (pos = 0x30; pos + 16 <= end; pos += 16) {
		if (le32(fw + pos + 4) != 0 && le32(fw + pos + 8) == 0) {
			end = pos + 16;
			break;
		}
	}
	unsigned n = (end - 0x30) / 16;
	if (n == 0 || n > 16)
		return 0;
	p[0] = (struct part){ le32(fw), le32(fw + 4), le32(fw + 8), le32(fw + 0x18) };
	p[1] = (struct part){ le32(fw + 12), le32(fw + 16), le32(fw + 20), le32(fw + 0x1c) };
	for (unsigned i = 0; i < n; i++) {
		const uint8_t *e = fw + 0x30 + i * 16;
		p[2 + i] = (struct part){ le32(e + 8), le32(e), le32(e + 4), le32(e + 12) };
	}
	*count = 2 + n;
	for (unsigned i = 0; i < *count; i++)
		if (p[i].size && p[i].bin + p[i].size + 1 > sizeof(nvt_fw))
			return 0;
	return 1;
}

static void crc_bank(uint32_t des, uint32_t len_reg, uint32_t golden, const struct part *p)
{
	uint8_t b[4];
	b[0] = (uint8_t)p->sram; b[1] = (uint8_t)(p->sram >> 8); b[2] = (uint8_t)(p->sram >> 16);
	nvt_write(des, b, 3);
	b[0] = (uint8_t)p->size; b[1] = (uint8_t)(p->size >> 8); b[2] = (uint8_t)(p->size >> 16);
	nvt_write(len_reg, b, 3);
	b[0] = (uint8_t)p->crc; b[1] = (uint8_t)(p->crc >> 8);
	b[2] = (uint8_t)(p->crc >> 16); b[3] = (uint8_t)(p->crc >> 24);
	nvt_write(golden, b, 4);
}

void shim_main(uint64_t dtb, uint64_t entry_el)
{
	struct part parts[18];
	unsigned count = 0;
	uint8_t id[6], st[6], fwi[2];
	(void)dtb; (void)entry_el;

	con_clear(BLUE);
	con_str("LAPIS", "tnvt v2: NT38771 fast load + Android ILM-skip path (timing test)");
	con_skip();

	/* pins 68..71 to GPIO: CS high, CLK/MOSI low outputs, MISO input */
	uint32_t mode = rd(GPIO + GPIO_MODE), dir = rd(GPIO + GPIO_DIR);
	do_idle = (rd(GPIO + GPIO_DO) & ~(CLK | MOSI)) | CS;
	wr(GPIO + GPIO_DO, do_idle);
	wr(GPIO + GPIO_DIR, (dir & ~MISO) | CLK | CS | MOSI);
	wr(GPIO + GPIO_MODE, mode & 0x0000ffffu);
	udelay(1000);
	con_hex2("GPIO", "mode=", mode, "dir=", dir);

	/* speed check: 1 KiB worth of tx bits */
	uint64_t t0 = ticks();
	set_page(NVT_CHIP_ID);
	cs_low();
	for (int i = 0; i < 1024; i++)
		tx_byte(0);
	cs_high();
	uint32_t us1k = us_since(t0);

	/* Android's chip check: reset 0x69, 5 ms, six zeros at 0x3F004, read ID */
	nvt_write_u8(NVT_RESET, 0x69);
	udelay(5000);
	for (int i = 0; i < 6; i++)
		id[i] = 0;
	nvt_write(NVT_CHIP_ID, id, 6);
	nvt_read(NVT_CHIP_ID, id, 6);
	con_hex2("CHIP", "id345=", ((uint32_t)id[3] << 16) | (id[4] << 8) | id[5],
		 "us/KiB=", us1k);
	if (id[4] != 0x87 || id[5] != 0x03) {
		con_str("FAIL", "chip ID mismatch");
		goto out;
	}
	if (!parse(parts, &count)) {
		con_str("FAIL", "firmware table rejected");
		goto out;
	}
	udelay(1000000);		/* Android: ~1 s from chip check to load */

	con_hex2("PARTS", "count=", count, "ilm_size=", parts[0].size + 1);

	/* the load, timed from the bootloader reset to BOOT_RDY */
	uint64_t tr = ticks();
	nvt_write_u8(NVT_RESET, 0x69);
	udelay(5000);
	/* Android's screen-on path: DMA-CRC the ILM already in SRAM (BLD bank
	 * 0x3F108/0x3F10C/0x3F110, 0x3F10F <- 1, poll 0x3F129); flag 0x02 =
	 * resident and intact, so the ILM write (~92 KiB of the ~130) is skipped. */
	crc_bank(0x3f108, 0x3f10c, 0x3f110, &parts[0]);
	nvt_write_u8(0x3f10f, 0x01);
	uint8_t dma_flag = 0;
	for (int i = 0; i < 20; i++) {
		nvt_read(0x3f129, &dma_flag, 1);
		if (dma_flag == 0x02 || dma_flag == 0x03)
			break;
		udelay(1000);
	}
	int skip_ilm = dma_flag == 0x02;
	crc_bank(0x3f7b4, 0x3f7b8, 0x3f7bc, &parts[0]);
	crc_bank(0x3fb84, 0x3fb88, 0x3fb8c, &parts[1]);
	for (unsigned i = skip_ilm ? 1 : 0; i < count; i++) {
		uint32_t left = parts[i].size ? parts[i].size + 1 : 0;
		uint32_t bin = parts[i].bin, sram = parts[i].sram;
		while (left) {
			uint32_t n = left > NVT_XFER_MAX ? NVT_XFER_MAX : left;
			nvt_write(sram, nvt_fw + bin, n);
			left -= n;
			bin += n;
			sram += n;
		}
	}
	nvt_write_u8(NVT_EVENT_BUF + 0x60, 0x00);
	nvt_write_u8(NVT_EVENT_BUF + 0x50, 0xae);
	nvt_write_u8(NVT_BOOT_READY, 1);
	uint32_t load_ms = us_since(tr) / 1000;
	udelay(5000);

	/* poll the reset-complete state like Android (10 ms steps, here 1 s) */
	uint32_t t_ok = 0, state = 0;
	uint64_t tp = ticks();
	for (int i = 0; i < 100; i++) {
		nvt_read(NVT_EVENT_BUF + 0x60, st, 6);
		state = st[0];
		if (state >= 0xa0 && state <= 0xaf) {
			t_ok = us_since(tp) / 1000 + 1;
			break;
		}
		udelay(10000);
	}
	nvt_read(NVT_EVENT_BUF + 0x78, fwi, 2);
	con_hex2("LOAD", "reset->rdy_ms=", load_ms, "dma_flag/skip=", ((uint32_t)dma_flag << 8) | (uint32_t)skip_ilm);
	con_hex2("STATE", "state=", state, "ok_after_ms=", t_ok);
	con_hex2("FWINFO", "ver/~ver=", ((uint32_t)fwi[0] << 8) | fwi[1],
		 "st1..3=", ((uint32_t)st[1] << 16) | (st[2] << 8) | st[3]);
	con_str("KEY ", (state >= 0xa0 && state <= 0xaf) ?
		"FIRMWARE BOOTED -> the slow bit-bang was the problem" :
		"still not booted -> not (only) the timing");
out:
	con_str("DONE", "Power+Vol-down to recover");
	for (;;)
		__asm__ volatile("wfe");
}

void exc_report(uint64_t slot, uint64_t esr, uint64_t elr, uint64_t far)
{
	con_skip();
	con_hex("EXC slot", slot);
	con_hex("ESR", esr);
	con_hex("ELR", elr);
	con_hex("FAR", far);
	for (;;)
		__asm__ volatile("wfe");
}
